#include "libft.h"

int	ft_memcmp(const void *s1, const void *s2, size_t n)
{
	size_t			i;
	unsigned char	*a;
	unsigned char	*b;

	i = 0;
	a = (unsigned char *)s1;
	b = (unsigned char *)s2;
	while (i < n && a[i] == b[i])
		i++;
	if (i == n)
		return (0);
	return ((unsigned char)a[i] - (unsigned char)b[i]);
}
