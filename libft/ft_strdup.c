#include "libft.h"

char	*ft_strdup(const char *src)
{
	size_t	i;
	char	*copy;

	copy = malloc(ft_strlen(src) + 1);
	if (!copy)
		return (copy);
	i = 0;
	while (src[i])
	{
		copy[i] = src[i];
		i++;
	}
	copy[i] = 0;
	return (copy);
}
